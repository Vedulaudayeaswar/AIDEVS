def pascal(name):
    return "".join(part.capitalize() for part in name.split("_"))


def plural(name):
    if name.endswith("y") and len(name) > 1 and name[-2] not in "aeiou":
        return name[:-1] + "ies"
    if name.endswith(("s", "x", "ch", "sh")):
        return name + "es"
    return name + "s"


def resource_config(entities):
    return {
        e["name"]: {
            "label": e["label"], "path": plural(e["name"]), "fields": e["fields"],
            "permissions": e["permissions"],
        } for e in entities
    }


def sample_payload(entity):
    if entity.get("sample_data"):
        row = dict(entity["sample_data"][0])
    else:
        row = {}
    defaults = {"string": "Sample", "text": "Sample text", "integer": 1, "number": 9.99,
                "boolean": True, "date": "2026-01-01", "datetime": "2026-01-01T10:00:00",
                "email": "person@example.com", "url": "https://example.com",
                "image": "https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=800"}
    for field in entity["fields"]:
        if field["name"] not in row or row[field["name"]] in (None, ""):
            row[field["name"]] = defaults[field["type"]]
    return row


