"""Compile project entities into a runnable Flask + SQLAlchemy backend.

The AI designs *what* data the app needs (entities, fields, permissions);
this module deterministically writes *how* (models, validated CRUD APIs,
auth, migrations, seed data and tests). That keeps generated backends
functional and reviewable instead of trusting free-form LLM code.
"""
