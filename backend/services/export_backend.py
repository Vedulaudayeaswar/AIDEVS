def migration_sql(entities):
    """Initial schema DDL for SQLite and PostgreSQL, compiled by SQLAlchemy."""
    md = MetaData()
    Table("users", md, Column("id", Integer, primary_key=True),
          Column("email", String(254), nullable=False, unique=True, index=True),
          Column("name", String(120), nullable=False), Column("password_hash", String(100), nullable=False),
          Column("role", String(20), nullable=False), Column("created_at", DateTime(timezone=True)))
    for e in entities:
        cols = [Column("id", Integer, primary_key=True),
                Column("owner_id", Integer, ForeignKey("users.id", ondelete="SET NULL"), index=True)]
        cols += [Column(f["name"], COLUMN_SA[f["type"]](), nullable=not f["required"]) for f in e["fields"]]
        cols += [Column("created_at", DateTime(timezone=True)), Column("updated_at", DateTime(timezone=True))]
        Table(plural(e["name"]), md, *cols)
    out = {}
    for label, dialect in (("sqlite", sqlite.dialect()), ("postgresql", postgresql.dialect())):
        stmts = []
        for table in md.sorted_tables:
            stmts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
            for index in table.indexes:
                stmts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        out[label] = "-- Initial schema generated by AIDevs\n\n" + "\n\n".join(stmts) + "\n"
    return out


